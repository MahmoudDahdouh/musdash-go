// Build packs that need no Dockerfile: a builder reads the repository and
// works out how to build it.
//
// A builder is a program from somewhere else that reads files somebody
// else wrote. It is never installed on a server. It runs in a container
// made from an image musdash builds the first time it is needed, and that
// container can see the checkout and nothing else of the server: no Docker
// socket, no capabilities, a read-only root. What comes out of it is a
// plan; the image itself is built by `docker build`, as for a Dockerfile.
const (
	PackNixpacks = "nixpacks"
	PackRailpack = "railpack"
)

// ValidPack reports whether name is a build pack.
func ValidPack(name string) bool {
	switch name {
	case PackDockerfile, PackStatic, PackNixpacks, PackRailpack:
		return true
	}
	return false
}

// ListensOnPORT reports whether apps built with a pack read the port to
// listen on from the PORT variable, as both builders arrange.
func ListensOnPORT(pack string) bool { return pack == PackNixpacks || pack == PackRailpack }

// builder is one of the tools: where its release is, and what the file of
// each architecture must hash to. A build must not change because a
// release file was replaced.
type builder struct {
	name    string // also the name of its command
	label   string
	version string
	// file is the release file's address with %s for the architecture as
	// the project names it.
	file   string
	assets map[string]asset // Docker's architecture name → the file
}

type asset struct {
	arch string // as it appears in the file name
	sum  string // SHA-256 of the file
}

